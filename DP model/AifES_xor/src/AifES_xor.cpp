bool capture_audio() {
    size_t offset = 0;

    while (offset < AUDIO_SAMPLES) {
        if (Microphone_PDM::instance().samplesAvailable()) {
            int16_t temp[256];

            if (Microphone_PDM::instance().copySamples(temp)) {
                size_t count = Microphone_PDM::instance().getNumberOfSamples();

                for (size_t i = 0; i < count && offset < AUDIO_SAMPLES; i++) {
                    sampleBuffer[offset++] = temp[i];
                }
            }
        }
    }

    return true;
}

